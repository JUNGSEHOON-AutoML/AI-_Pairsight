// Generates app/theme.css (Tailwind v4 @theme) from replica/design/tokens.json.
// tokens.json is the single source of truth; components only use the utilities this file defines.
// Run: npm run theme
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, "../../replica/design/tokens.json"), "utf8"));

const lines = ["/* Generated by scripts/gen-theme.mjs from replica/design/tokens.json. Do not edit. */", "@theme {"];
for (const [k, v] of Object.entries(tokens.color)) lines.push(`  --color-${k}: ${v};`);
lines.push(`  --font-sans: ${tokens.font.sans};`);
lines.push(`  --font-mono: ${tokens.font.mono};`);
for (const [k, v] of Object.entries(tokens.type)) {
  lines.push(`  --text-${k}: ${v.size}px;`);
  lines.push(`  --text-${k}--line-height: ${v.line}px;`);
  lines.push(`  --text-${k}--font-weight: ${v.weight};`);
}
for (const [k, v] of Object.entries(tokens.radius)) lines.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(tokens.shadow)) lines.push(`  --shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.layout.breakpoints)) lines.push(`  --breakpoint-${k}: ${v}px;`);
lines.push(`  --container-content: ${tokens.layout.content_max}px;`);
lines.push(`  --container-reading: ${tokens.layout.reading_max}px;`);
lines.push(`  --ease-brand: ${tokens.motion.ease};`);
lines.push(`  --animate-spin: spin 1s linear infinite;`);
lines.push("}");
lines.push("");
lines.push(":root {");
lines.push(`  --motion-fast: ${tokens.motion.fast};`);
lines.push(`  --motion-base: ${tokens.motion.base};`);
lines.push(`  --header-h: ${tokens.layout.header_h}px;`);
lines.push("}");

writeFileSync(join(here, "../app/theme.css"), lines.join("\n") + "\n");
console.log(`wrote app/theme.css (${Object.keys(tokens.color).length} colours)`);
