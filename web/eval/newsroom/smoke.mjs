// Uses a copy of the private database and disposable operator credentials. Never approves a live case.
import { createRequire } from "node:module";
import { mkdtemp,writeFile,copyFile,mkdir,rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join,resolve } from "node:path";
import { randomBytes,scryptSync } from "node:crypto";
import { spawn } from "node:child_process";
import assert from "node:assert/strict";
const web=process.cwd(),claw=process.env.CLAW3D_DIR;
if(!claw)throw Error("CLAW3D_DIR required");
const {chromium}=createRequire(join(claw,"package.json"))("@playwright/test");
const dir=await mkdtemp(join(tmpdir(),"pairsight-newsroom-ui-")),db=join(dir,"cases.sqlite"),users=join(dir,"operators.json");
const password=randomBytes(24).toString("hex"),salt=randomBytes(16).toString("hex");
await copyFile(join(web,".newsroom","cases.sqlite"),db);
await writeFile(users,JSON.stringify([{id:"browser-test-only",salt,digest:scryptSync(password,salt,64).toString("hex")}]),{mode:0o600});
const port=Number(process.env.NEWSROOM_TEST_PORT??3012),base="http://127.0.0.1:"+port,office=process.env.NEWSROOM_TEST_OFFICE??"http://127.0.0.1:3460";
const child=spawn(process.execPath,["node_modules/next/dist/bin/next","start","--hostname","127.0.0.1","--port",String(port)],{cwd:web,
  env:{PATH:process.env.PATH,HOME:process.env.HOME,NODE_ENV:"production",PAIRSIGHT_CASE_DB:db,PAIRSIGHT_OPERATOR_FILE:users},stdio:"ignore"});
const output=resolve(process.env.NEWSROOM_SCREEN_DIR??"../replica/clone-screens/cases");await mkdir(output,{recursive:true});
let browser;
try {
  let ready=false;for(let i=0;i<120;i++){try{if((await fetch(base+"/api/operator/session")).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,500));}
  assert(ready,"test server ready");
  assert.equal((await fetch(base+"/api/operator/cases")).status,401);
  assert.equal((await fetch(base+"/api/checks",{method:"POST"})).status,404);
  const csrf=await fetch(base+"/api/operator/session",{method:"POST",headers:{origin:"https://untrusted.example","x-newsroom-request":"1","content-type":"application/json"},body:"{}"});assert.equal(csrf.status,403);
  browser=await chromium.launch({executablePath:process.env.CHROME_PATH??"/usr/bin/google-chrome",headless:true,args:["--no-sandbox","--enable-unsafe-swiftshader","--disable-dev-shm-usage"]});
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(base+"/newsroom");await page.waitForURL("**/newsroom/login");
  await page.getByLabel("운영자 ID").fill("browser-test-only");await page.getByLabel("비밀번호",{exact:true}).fill(password);
  await page.getByRole("button",{name:"편집국 로그인"}).click();await page.waitForURL(base+"/newsroom");
  await page.getByRole("heading",{name:"부서별 사건"}).waitFor();
  await page.waitForTimeout(5500);
  assert.equal(await page.getByText("진행 상태 갱신에 실패했어요. 마지막 확인한 기록을 보여줘요.",{exact:true}).count(),0);
  const current=await page.request.get(base+"/api/operator/cases");const data=await current.json();assert.equal(data.cases.length,3);
  await page.screenshot({path:join(output,"operator-1280.png"),fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:join(output,"operator-390.png"),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"operator mobile overflow");
  await page.goto(base+"/newsroom/new");await page.getByRole("button",{name:"사건 접수하고 부서 검토 시작"}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"intake mobile overflow");
  await page.screenshot({path:join(output,"intake-390.png"),fullPage:true});
  const pending=data.cases.find(c=>c.status==="awaiting_approval");assert(pending);
  await page.goto(base+"/newsroom/"+pending.id);await page.getByRole("heading",{name:"사람 검토",exact:true}).waitFor();
  await page.screenshot({path:join(output,"case-390.png"),fullPage:true});
  const stale=await page.request.post(base+"/api/operator/cases/"+pending.id,{headers:{origin:base,"x-newsroom-request":"1"},data:{action:"approve",revision:-1,title:"test",summary:"test"}});
  assert.equal(stale.status(),400);
  await page.goto(base+"/cases");await page.getByText("사례 0건",{exact:true}).waitFor();
  assert.equal(await page.getByText("개발용 모의 데이터",{exact:true}).count(),0);
  await page.screenshot({path:join(output,"public-390.png"),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"public mobile overflow");
  const hidden=await page.request.get(base+"/cases/"+pending.id), hiddenBody=await hidden.text();
  assert([200,404].includes(hidden.status()));assert(!hiddenBody.includes(pending.input.claim));assert(hiddenBody.includes('content="noindex"'));
  const fixture=await page.request.get(base+"/dev/fixtures"),fixtureBody=await fixture.text();assert([200,404].includes(fixture.status()));assert(fixtureBody.includes('content="noindex"'));assert(!fixtureBody.includes("이 샘플로 검사"));
  for(const [method,path] of [["POST","/api/newsroom"],["GET","/api/studio"],["POST","/api/runtime/custom"]])assert.equal((await fetch(office+path,{method})).status,403);
  await page.setViewportSize({width:1440,height:960});await page.goto(office+"/newsroom");
  await page.getByRole("navigation",{name:"편집국 부서"}).getByRole("button").first().waitFor();
  assert.equal(await page.getByRole("navigation",{name:"편집국 부서"}).getByRole("button").count(),9);
  const snapshot=await (await page.request.get(office+"/api/newsroom")).json();assert.equal(snapshot.cases.length,3);assert.equal(snapshot.readOnly,true);
  await page.waitForTimeout(3000);await page.screenshot({path:join(output,"claw3d-1440.png"),fullPage:true});
  await page.getByRole("navigation",{name:"편집국 부서"}).getByRole("button",{name:"T&S"}).click();
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:join(output,"claw3d-390.png"),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"3D mobile overflow");
  assert.equal(errors.length,0,"browser errors");
  const result={operatorAuth:true,csrf:true,realCases:3,unapprovedHidden:true,fixturesHidden:true,mobileOverflow:false,departments:9,viewerMutationsBlocked:true,browserErrors:errors.length};
  await writeFile(join(output,"result.json"),JSON.stringify(result,null,2)+"\n");console.log(JSON.stringify(result));
}finally{
  await browser?.close();child.kill("SIGTERM");
  await new Promise(resolve=>child.exitCode!==null?resolve():child.once("exit",resolve));
  await rm(dir,{recursive:true,force:true});
}
